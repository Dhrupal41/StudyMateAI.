def get_prompt_value(prompt, field):
    """Read a value such as 'Subject: Python' from a prompt."""

    pattern = rf"^\s*{re.escape(field)}:\s*(.+)$"

    match = re.search(
        pattern,
        prompt,
        re.IGNORECASE | re.MULTILINE
    )

    return match.group(1).strip() if match else ""


